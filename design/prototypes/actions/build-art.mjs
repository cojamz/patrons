// Pulls the real pixel art the mocks need out of src/v4/art (read-only) into art.js, a plain script for file:// pages.
// Run from the repo root: node design/prototypes/actions/build-art.mjs
import fs from 'node:fs';
import SETS from '../../../src/v4/art/icons/index.js';
import { SPHERES, NEUTRALS } from '../../../src/v4/art/index.js';

const want = ['joint-venture', 'gold.rush', 'gold.discount', 'gold.steal', 'gold.windfall', 'strike',
  'red.scout', 'red.turnout', 'red.hire', 'red.hireup', 'red.trade', 'red.take',
  'market.bargain', 'market.restock', 'market.showroom', 'market.clearance', 'market.pricecheck', 'market.spree',
  'echo.hum', 'echo.chant', 'echo.echo', 'echo.encore', 'echo.refrain', 'echo.eternity', 'pickpocket'];
const pick = id => { const i = SETS.find(x => x.id === id); if (!i) throw new Error('missing ' + id); return { id: i.id, name: i.name, kind: i.kind, sphere: i.sphere, px: i.px, palette: i.palette || null }; };
const out = {
  SPHERES, NEUTRALS,
  ACTIONS: Object.fromEntries(want.map(id => [id, pick(id)])),
  EMOJI: Object.fromEntries(['cat', 'robot', 'frog', 'ghost'].map(id => { const e = SETS.find(x => x.kind === 'emoji' && x.id === id); return [id, { px: e.px, em: e.em, palette: e.palette }]; })),
  LEADER: (() => { const l = SETS.find(x => x.kind === 'leader'); return l ? { px: l.px, base: l.base, emblem: l.emblem } : null; })(),
  FOLLOWER: (() => { const f = SETS.find(x => x.kind === 'follower'); return f ? { px: f.px, base: f.base } : null; })(),
};
fs.writeFileSync(new URL('./art.js', import.meta.url), `// Generated by build-art.mjs from src/v4/art (do not edit).\nwindow.ART = ${JSON.stringify(out)};\n`);
console.log('art.js written:', Object.keys(out.ACTIONS).length, 'actions');
