// Imports the pixel-art icon sets drawn under design/prototypes/pixel-art/ (classic scripts that set
// globalThis.CultIcons, one per file: icons.js, icons-<sphere>.js) into src/v4/art/icons/ as ES modules, and
// writes src/v4/art/icons/index.js listing them. Run after a drawing batch lands: node scripts/v4-art-import.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const SRC = 'design/prototypes/pixel-art', OUT = 'src/v4/art/icons';
const files = readdirSync(SRC).filter(f => /^icons(-[\w-]+)?\.js$/.test(f)).sort();
const names = [];
for (const f of files) {
  const box = { globalThis: {}, window: undefined, module: undefined };
  box.globalThis = box;
  vm.runInNewContext(readFileSync(`${SRC}/${f}`, 'utf8'), box, { filename: f });
  const api = box.CultIcons;
  if (!api || !Array.isArray(api.ICONS)) { console.warn(`${f}: no CultIcons.ICONS, skipped`); continue; }
  const bad = api.ICONS.flatMap(i => (api.validate ? api.validate(i) : []));
  if (bad.length) { console.warn(`${f}: ${bad.length} problems, skipped:\n  ${bad.slice(0, 5).join('\n  ')}`); continue; }
  const name = f === 'icons.js' ? 'calibration' : f.slice('icons-'.length, -3);
  const data = api.ICONS.map(({ id, name: nm, kind, sphere, px }) => ({ id, name: nm, kind, sphere, px }));
  writeFileSync(`${OUT}/${name}.js`, `// Generated by scripts/v4-art-import.mjs from ${SRC}/${f}. Do not edit; redraw there and re-import.\nexport default ${JSON.stringify(data, null, 1)};\n`);
  names.push(name);
  console.log(`${f} → ${OUT}/${name}.js (${data.length} icons)`);
}
const id = n => `set_${n.replace(/\W/g, '_')}`;
writeFileSync(`${OUT}/index.js`, `// Generated by scripts/v4-art-import.mjs: every imported icon set.\n${names.map(n => `import ${id(n)} from './${n}.js';`).join('\n')}\nexport default [${names.map(id).join(', ')}].flat();\n`);
