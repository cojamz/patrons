// Imports the pixel art drawn under design/prototypes/pixel-art/ into src/v4/art/icons/ as ES modules:
//  - icons.js (calibration, globalThis.CultIcons) and icons-<batch>.js (globalThis.CultIconBatches[<batch>]; grids in
//    `px` or `rows`; ids are engine ids like "gold.banker"); every icon must pass CultIcons.validate;
//  - emojis.js (globalThis.CultMinions): each player's minion (16×16) and its leader emblem (8×8), with palettes;
//  - leaders.js (globalThis.CultLeaders), when it lands: 32×32 leader figures.
// Then writes src/v4/art/icons/index.js. Run after a batch lands: node scripts/v4-art-import.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import vm from 'node:vm';

const SRC = 'design/prototypes/pixel-art', OUT = 'src/v4/art/icons';
const box = {};
box.globalThis = box;
const run = f => vm.runInNewContext(readFileSync(`${SRC}/${f}`, 'utf8'), box, { filename: f });
const write = (name, data, from) => writeFileSync(`${OUT}/${name}.js`, `// Generated by scripts/v4-art-import.mjs from ${SRC}/${from}. Do not edit; redraw there and re-import.\nexport default ${JSON.stringify(data)};\n`);
const names = [];

run('icons.js');
const api = box.CultIcons;
const clean = i => ({ id: i.id, name: i.name, kind: i.kind, sphere: i.sphere, px: i.px || i.rows });
// The calibration set is keyed by kebab names. A card renamed since (action names, 2026-10-14) is rekeyed to its
// engine id and its new name here, so the game keeps its drawing; the design mocks keep using the kebab ids.
const CAL_KEYS = {
  'joint-venture': ['gold.jv', 'Kickback'], strike: ['gold.strike', 'Double Down'],
  pickpocket: ['thieves.pickpocket', 'Help Yourself'], heist: ['thieves.heist', 'Poach'],
};
const calib = i => (CAL_KEYS[i.id] ? { ...clean(i), id: CAL_KEYS[i.id][0], name: CAL_KEYS[i.id][1] } : clean(i));
write('calibration', api.ICONS.map(calib), 'icons.js');
names.push('calibration');
console.log(`icons.js → calibration (${api.ICONS.length})`);

for (const f of readdirSync(SRC).filter(x => /^icons-[\w-]+\.js$/.test(x)).sort()) {
  const before = new Set(Object.keys(box.CultIconBatches || {}));
  try { run(f); } catch (e) { console.warn(`${f}: failed to load (${e.message}), skipped`); continue; }
  const added = Object.keys(box.CultIconBatches || {}).filter(k => !before.has(k));
  for (const batch of added) {
    const list = box.CultIconBatches[batch].map(clean);
    const ok = [], bad = [];
    for (const i of list) { const errs = api.validate({ ...i }); (errs.length ? bad : ok).push(errs.length ? `${i.id}: ${errs[0]}` : i); }
    if (bad.length) console.warn(`${f} [${batch}]: ${bad.length} icons fail validate, left out:\n  ${bad.slice(0, 6).join('\n  ')}`);
    const name = `batch-${batch}`;
    write(name, ok, f);
    names.push(name);
    console.log(`${f} → ${name} (${ok.length})`);
  }
}

if (existsSync(`${SRC}/emojis.js`)) {
  run('emojis.js');
  const M = box.CultMinions;
  const errs = M.validateAll ? M.validateAll() : [];
  // an unused palette slot is untidy, not broken; anything else (bad keys, sizes) leaves the emoji out
  const bad = new Set(errs.filter(e => !/never used/.test(e)).map(e => e.split(/[ :]/)[0]));
  const list = (M.ICONS || M.MINIONS).filter(m => !bad.has(m.id)).map(m => ({ id: m.id, name: m.name, emoji: m.emoji, kind: 'emoji', px: m.px, em: m.em, palette: M.palette(m) }));
  if (errs.length) console.warn(`emojis.js: ${errs.length} notes, ${bad.size} left out (${[...bad].join(', ')}):\n  ${errs.slice(0, 6).join('\n  ')}`);
  write('emojis', list, 'emojis.js');
  names.push('emojis');
  console.log(`emojis.js → emojis (${list.length})`);
}
if (existsSync(`${SRC}/leaders.js`)) {
  try {
    run('leaders.js');
    const L = box.CultLeaders;
    const errs = L.validate ? L.validate().filter(e => !/never used|alien/.test(e)) : [];
    if (errs.length) console.warn(`leaders.js: ${errs.length} problems:\n  ${errs.slice(0, 4).join('\n  ')}`);
    // the neutral keys of the leader palette (digits are the seat accent, filled in by the screen)
    const pal = L.accentPalette('#808080');
    const base = Object.fromEntries(Object.entries(pal).filter(([k]) => !/[123]/.test(k)));
    write('leaders', [{ id: '_leader', kind: 'leader', px: L.LEADER, base, panel: L.PANEL, emblem: L.EMBLEM, accents: L.SEAT_ACCENTS },
      { id: '_follower', kind: 'follower', px: L.FOLLOWER, base: { k: base.k, w: '#f6eedb', c: '#cbbd9c' } }], 'leaders.js');
    names.push('leaders');
    console.log('leaders.js → leaders (leader 32×32, follower 10×10)');
  } catch (e) { console.warn(`leaders.js: ${e.message}, skipped`); }
}
const v = n => `set_${n.replace(/\W/g, '_')}`;
writeFileSync(`${OUT}/index.js`, `// Generated by scripts/v4-art-import.mjs: every imported icon set.\n${names.map(n => `import ${v(n)} from './${n}.js';`).join('\n')}\nexport default [${names.map(v).join(', ')}].flat();\n`);
