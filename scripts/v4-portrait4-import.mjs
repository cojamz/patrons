// Scene portraits into the game: design/prototypes/scenes/out/*.json (later files win) → src/v4/art/portraits4/index.js.
// Each entry is { id, name, sphere, grid: [rows of one-char keys, '.' clear], pal: { key: '#hex' } }, any square size.
//   node scripts/v4-portrait4-import.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = 'design/prototypes/scenes/out';
const files = existsSync(dir) ? readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(f => `${dir}/${f}`) : [];
const all = new Map();
for (const f of files) {
  for (const ic of JSON.parse(readFileSync(f, 'utf8'))) {
    const n = ic.grid.length;
    if (ic.grid.some(r => r.length !== n)) throw new Error(`${f}: ${ic.id} is not square`);
    for (const r of ic.grid) for (const ch of r) if (ch !== '.' && !ic.pal[ch]) throw new Error(`${f}: ${ic.id} key ${ch} has no colour`);
    all.set(ic.id, { id: ic.id, name: ic.name, kind: ic.kind || 'member', sphere: ic.sphere, px: ic.grid, pal: ic.pal });
  }
}
const list = [...all.values()].sort((a, b) => a.id.localeCompare(b.id));
writeFileSync('src/v4/art/portraits4/index.js', `// Generated by scripts/v4-portrait4-import.mjs from ${dir}. Do not edit; redraw there and re-import.\nexport default ${JSON.stringify(list)};\n`);
console.log(`${list.length} portraits (scenes)`);
