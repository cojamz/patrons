// Portraits into the game: design/prototypes/art-v2/portraits/out-*.json (and reference.json) → src/v4/art/portraits/index.js.
//   node scripts/v4-portrait-import.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = 'design/prototypes/art-v2/portraits';
const all = new Map();
for (const f of ['reference.json', ...readdirSync(dir).filter(f => /^out-.*\.json$/.test(f)).sort()]) {
  for (const ic of JSON.parse(readFileSync(`${dir}/${f}`, 'utf8'))) {
    if (ic.px.length !== 32 || ic.px.some(r => r.length !== 32)) throw new Error(`${f}: ${ic.id} is not 32×32`);
    all.set(ic.id, { id: ic.id, name: ic.name, kind: ic.kind || 'member', px: ic.px });
  }
}
const list = [...all.values()].sort((a, b) => a.id.localeCompare(b.id));
writeFileSync('src/v4/art/portraits/index.js', `// Generated by scripts/v4-portrait-import.mjs from ${dir}. Do not edit; redraw there and re-import.\nexport default ${JSON.stringify(list)};\n`);
console.log(`${list.length} portraits`);
