// Portraits v3 into the game: design/prototypes/art-v3/samples.json and out/*.json (later files win) → src/v4/art/portraits3/index.js.
//   node scripts/v4-portrait3-import.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = 'design/prototypes/art-v3';
const files = [`${dir}/samples.json`, ...(existsSync(`${dir}/out`) ? readdirSync(`${dir}/out`).filter(f => f.endsWith('.json')).sort().map(f => `${dir}/out/${f}`) : [])];
const all = new Map();
for (const f of files) {
  if (!existsSync(f)) continue;
  for (const ic of JSON.parse(readFileSync(f, 'utf8'))) {
    if (ic.px.length !== 48 || ic.px.some(r => r.length !== 48)) throw new Error(`${f}: ${ic.id} is not 48×48`);
    all.set(ic.id, { id: ic.id, name: ic.name, kind: ic.kind || 'member', sphere: ic.sphere, people: ic.people, accent: ic.accent, px: ic.px });
  }
}
const list = [...all.values()].sort((a, b) => a.id.localeCompare(b.id));
writeFileSync('src/v4/art/portraits3/index.js', `// Generated by scripts/v4-portrait3-import.mjs from ${dir}. Do not edit; redraw there and re-import.\nexport default ${JSON.stringify(list)};\n`);
console.log(`${list.length} portraits (v3)`);
