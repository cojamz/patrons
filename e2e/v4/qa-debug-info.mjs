import { chromium } from 'playwright';
import { richSave } from './lib/rich-save.mjs';
import { answerChoice } from './lib/answer.mjs';
const base = 'http://127.0.0.1:5404';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const save = richSave(); const st = save.state;
const give = (pid, def) => { const c = Object.values(st.cards).find(x => x.def === def && !st.players.some(p => p.members.includes(x.uid))); if (!c) return; st.shop = st.shop.filter(u => u !== c.uid); st.pile = st.pile.filter(u => u !== c.uid); st.players[pid].members.push(c.uid); c.recruitedRound = 0; c.recruitedBy = pid; };
give(0, 'gold.thrift'); give(0, 'benders.frontrunner'); give(0, 'red.crowd');
st.pile.slice(0, 9).forEach((u, k) => give(1 + (k % 3), st.cards[u].def));
while (st.shop.length < 10 && st.pile.length) st.shop.push(st.pile.shift());
st.players[0].discount = 4;
const pg = await browser.newPage({ viewport: { width: 1270, height: 700 } });
await pg.goto(`${base}/?botDelay=20&intro=0`);
await pg.evaluate(v => localStorage.setItem('patrons.v4.local', JSON.stringify(v)), save);
await pg.reload();
await pg.waitForSelector('[data-home="resume"], .lt-shop .card[data-uid]');
if (await pg.$('[data-home="resume"]')) await pg.click('[data-home="resume"]');
await pg.waitForSelector('.lt-shop .card[data-uid]');
await pg.waitForTimeout(400);
await pg.mouse.move(4, 690);
const sp = await pg.$('.slot.can .base');
console.log('slot', await sp.evaluate(e => e.closest('[data-slot]').dataset.slot));
const bb = await sp.boundingBox();
await pg.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2);
for (let k = 0; k < 8 && !(await pg.$('.lt[data-phase="buy"][data-yours="1"]')); k++) {
  const at = await pg.evaluate(() => ({ phase: document.querySelector('.app.game').dataset.phase, yours: document.querySelector('.app.game').dataset.yours, ids: [...document.querySelectorAll('[data-option]')].map(e => e.getAttribute('data-option')), prompt: document.querySelector('[data-prompt]')?.textContent }));
  const did = await answerChoice(pg);
  console.log(k, JSON.stringify(at), '->', JSON.stringify(did));
  await pg.waitForTimeout(250);
}
const end = await pg.evaluate(() => ({ phase: document.querySelector('.app.game').dataset.phase, yours: document.querySelector('.app.game').dataset.yours, ids: [...document.querySelectorAll('[data-option]')].map(e => e.getAttribute('data-option')) }));
console.log('end', JSON.stringify(end));
await pg.screenshot({ path: '/tmp/claude-0/-home-user-patrons/5ebe88de-0e49-593c-823a-8e25da0176c7/scratchpad/w/info-debug.png' });
await browser.close();
